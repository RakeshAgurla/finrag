"""Side-by-side retrieval comparison on the real corpus.

Runs the same queries through both embedding backends and writes the output to
evals/examples/. The point is to show what the offline hash fallback actually
costs, on real filings rather than the fixture.

The fixture ablation in evals/results.json measures ranking quality against
labelled data. This measures something the fixture cannot: whether retrieval
finds the right *document* at all when the query shares no vocabulary with the
answer.

    python -m finrag.eval.compare_backends
    python -m finrag.eval.compare_backends --top-k 5 --out evals/examples/mine.md
"""

from __future__ import annotations

import argparse
import os
import time

# faiss-cpu and torch each bundle an OpenMP runtime; loading both in one
# process aborts on macOS. This script compares two backends in a single
# run, so it hits that. At 833 chunks the numpy dot product is fast enough
# that FAISS buys nothing here.
os.environ.setdefault("KMP_DUPLICATE_LIB_OK", "TRUE")
from pathlib import Path

from finrag.config import RetrievalConfig
from finrag.index.embed import HashEmbedder, build_embedder
from finrag.index.hybrid import HybridRetriever, load_chunks

# Chosen to separate lexical from semantic retrieval:
#   - "operating income" appears verbatim in filings; BM25 alone handles it
#   - "artificial intelligence" requires knowing Item 1 Business discusses
#     strategy; no character overlap will find it
#   - "ASC 606" is a pure identifier; dense retrieval is expected to be weak
QUERIES = [
    "what supply chain risks were disclosed",
    "how did operating income change",
    "what does the company say about artificial intelligence",
    "revenue recognition policy under ASC 606",
    "how much did the company spend on research and development",
    "what legal proceedings are pending",
]


def run_backend(name: str, chunks, top_k: int) -> tuple[dict, float, float]:
    embedder = HashEmbedder() if name == "hash" else build_embedder()

    t0 = time.perf_counter()
    retriever = HybridRetriever(
        chunks, embedder=embedder, cfg=RetrievalConfig(rerank=False)
    )
    build_s = time.perf_counter() - t0

    results = {}
    latencies = []
    for query in QUERIES:
        t0 = time.perf_counter()
        hits = retriever.retrieve(query, top_k=top_k)
        latencies.append((time.perf_counter() - t0) * 1000)
        results[query] = hits

    latencies.sort()
    p95 = latencies[int(len(latencies) * 0.95) - 1] if latencies else 0.0
    return results, build_s, p95


def format_hit(hit) -> str:
    c = hit.chunk
    text = " ".join(c.text.split())[:110]
    ranks = []
    if hit.dense_rank:
        ranks.append(f"d{hit.dense_rank}")
    if hit.lexical_rank:
        ranks.append(f"l{hit.lexical_rank}")
    tag = f"({'/'.join(ranks)})" if ranks else "(fused)"
    return f"`{c.ticker} FY{c.fiscal_year} Item {c.section_item}` {tag} — {text}…"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--chunks", type=Path, default=Path("artifacts/index/chunks.jsonl"))
    parser.add_argument("--top-k", type=int, default=3)
    parser.add_argument("--out", type=Path, default=Path("evals/examples/backend_comparison.md"))
    args = parser.parse_args()

    if not args.chunks.exists():
        raise SystemExit(
            f"No corpus at {args.chunks}. Run `make ingest TICKERS=AAPL,MSFT` first."
        )

    chunks = load_chunks(args.chunks)
    tickers = sorted({c.ticker for c in chunks})
    years = sorted({c.fiscal_year for c in chunks})
    print(f"corpus: {len(chunks)} chunks | {', '.join(tickers)} | FY{years[0]}-{years[-1]}")

    print("running hash backend…")
    hash_results, hash_build, hash_p95 = run_backend("hash", chunks, args.top_k)

    print("running sentence-transformers backend…")
    st_results, st_build, st_p95 = run_backend("st", chunks, args.top_k)

    lines = [
        "# Backend comparison on real filings",
        "",
        "Generated by `python -m finrag.eval.compare_backends`.",
        "",
        (
            f"**Corpus:** {len(chunks)} chunks from {len(tickers)} companies "
            f"({', '.join(tickers)}), FY{years[0]}–FY{years[-1]}, ingested from EDGAR."
        ),
        "",
        "| | hash (offline) | bge-small-en-v1.5 |",
        "|---|---|---|",
        f"| index build | {hash_build:.1f}s | {st_build:.1f}s |",
        f"| query p95 | {hash_p95:.1f}ms | {st_p95:.1f}ms |",
        "",
        "Rank annotations show which retriever surfaced the chunk: `d` = dense,",
        "`l` = lexical. A chunk with only `l` was found by BM25 alone.",
        "",
        "---",
        "",
    ]

    for query in QUERIES:
        lines.append(f"### {query}")
        lines.append("")
        lines.append("**hash embeddings**")
        lines.append("")
        for hit in hash_results[query]:
            lines.append(f"- {format_hit(hit)}")
        lines.append("")
        lines.append("**sentence-transformers**")
        lines.append("")
        for hit in st_results[query]:
            lines.append(f"- {format_hit(hit)}")
        lines.append("")

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines))
    print(f"\nwritten to {args.out}")
    print(f"index build: hash {hash_build:.1f}s vs semantic {st_build:.1f}s")


if __name__ == "__main__":
    main()
